import { chromium } from 'playwright';
import { preview } from 'vite';
import { fileURLToPath } from 'node:url';
import { writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const root=fileURLToPath(new URL('../',import.meta.url));
const server=await preview({root,base:'/mission/',preview:{host:'127.0.0.1',port:0,strictPort:false},logLevel:'error'});
const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE||undefined,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const errors=[],failed=[],checks=[];
try {
  const page=await browser.newPage({viewport:{width:1280,height:900}});
  page.on('pageerror',e=>errors.push(e.stack));
  page.on('response',r=>{if(r.url().includes('/assets/')&&r.status()>=400)failed.push({url:r.url(),status:r.status()});});
  await page.route('https://fonts.googleapis.com/**',r=>r.abort());
  await page.route('https://fonts.gstatic.com/**',r=>r.abort());
  const url=`http://127.0.0.1:${server.httpServer.address().port}/mission/`;
  await page.goto(url);await page.locator('#begin:not([disabled])').waitFor();
  assert.equal(await page.evaluate(()=>typeof window.__KNOTZ_GAME__),'undefined');
  await page.locator('#begin').click();await page.locator('#hud').waitFor({state:'visible'});
  await page.keyboard.down('ArrowDown');await page.waitForTimeout(400);await page.keyboard.up('ArrowDown');
  await page.keyboard.press('p');await page.locator('#pause-panel').waitFor({state:'visible'});
  await page.locator('#pause-settings').click();await page.locator('#quality').selectOption('performance');
  await page.getByRole('button',{name:'Back to flight'}).click();
  await page.locator('#resume').click();await page.locator('#pause-panel').waitFor({state:'hidden'});
  assert.deepEqual(await page.locator('canvas').evaluate(c=>[c.width,c.height]),[640,360]);
  await page.screenshot({path:fileURLToPath(new URL('../../docs/evidence/mission/production.png',import.meta.url))});
  checks.push('production boots under /mission/ with optional fonts blocked and no dev hook','launch, input, pause, quality resize and resume work');
  await page.close();
  const missing=await browser.newPage();
  await missing.route('**/player-atlas.png',r=>r.abort());await missing.goto(url);
  await missing.locator('#error').waitFor({state:'visible'});
  assert.equal(await missing.locator('#begin').isDisabled(),true);
  checks.push('missing critical atlas gives a visible error and disables launch');await missing.close();
  const noGL=await browser.newPage();
  await noGL.addInitScript(()=>{const get=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){return type.startsWith('webgl')?null:get.call(this,type,...args);};});
  await noGL.goto(url);await noGL.locator('#error').waitFor({state:'visible'});assert.equal(await noGL.locator('#begin').isDisabled(),true);
  checks.push('unsupported WebGL is explained and launch disabled');await noGL.close();
  assert.deepEqual(errors,[]);assert.deepEqual(failed,[]);
  await writeFile(fileURLToPath(new URL('../../docs/evidence/mission/production-results.json',import.meta.url)),JSON.stringify({checks,errors,failed},null,2));
  console.log(JSON.stringify({checks,errors,failed},null,2));
} finally {await browser.close();await new Promise(resolve=>server.httpServer.close(resolve));}
